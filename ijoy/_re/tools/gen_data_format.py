"""Writes src/data_format.cpp: the joystick data format (c_dfDIJoystick2) that the original IJoy.dll
linked statically from the DirectX 7 dinput.lib. Read from the original's bytes: the DIDATAFORMAT at
0x1000d368 and its 164 DIOBJECTDATAFORMAT entries at 0x10005ee0.

Usage: python gen_data_format.py [path/to/IJoy.dll]
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
BASE = 0x10000000

GUIDS = {
    0x1000d4b0: "GUID_XAxis", 0x1000d4a0: "GUID_YAxis", 0x1000d490: "GUID_ZAxis",
    0x1000d480: "GUID_RxAxis", 0x1000d470: "GUID_RyAxis", 0x1000d460: "GUID_RzAxis",
    0x1000d450: "GUID_Slider", 0x1000d440: "GUID_Button", 0x1000d430: "GUID_POV",
}
TYPES = {0x80ffff03: "AXIS", 0x80ffff10: "POV", 0x80ffff0c: "BUTTON"}
ASPECTS = {0: "0", 0x100: "DIDOI_ASPECTPOSITION", 0x200: "DIDOI_ASPECTVELOCITY",
           0x300: "DIDOI_ASPECTACCEL", 0x400: "DIDOI_ASPECTFORCE"}


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "_re", "IJoy.dll")
    d = open(path, "rb").read()
    size, obj_size, flags, data_size, count, table = struct.unpack_from("<6I", d, 0x1000d368 - BASE)
    assert (size, obj_size, flags, data_size, count, table) == (0x18, 0x10, 1, 0x110, 164, 0x10005ee0)
    rows = []
    for i in range(count):
        guid, ofs, typ, fl = struct.unpack_from("<4I", d, table - BASE + i * 16)
        g = "&" + GUIDS[guid] if guid else "nullptr"
        rows.append("    {%s, 0x%x, %s, %s}," % (g, ofs, TYPES[typ], ASPECTS[fl]))
    out = os.path.join(ROOT, "src", "data_format.cpp")
    with open(out, "w", newline="\n") as f:
        f.write("// The joystick data format (c_dfDIJoystick2) the original linked from the DirectX 7\n"
                "// dinput.lib, entry for entry. Generated by _re/tools/gen_data_format.py.\n"
                "// Note the velocity, acceleration and force slider entries reuse the position slider\n"
                "// offsets (0x18, 0x1c); that is how that dinput.lib had it.\n"
                "#include \"ijoy_internal.h\"\n\n"
                "namespace {\n\n"
                "#ifndef DIDFT_OPTIONAL  // the SDK's dinput.h defines it for DirectInput 8 only\n"
                "#define DIDFT_OPTIONAL 0x80000000\n"
                "#endif\n\n"
                "const DWORD AXIS = DIDFT_OPTIONAL | DIDFT_AXIS | DIDFT_ANYINSTANCE;\n"
                "const DWORD POV = DIDFT_OPTIONAL | DIDFT_POV | DIDFT_ANYINSTANCE;\n"
                "const DWORD BUTTON = DIDFT_OPTIONAL | DIDFT_BUTTON | DIDFT_ANYINSTANCE;\n\n"
                "DIOBJECTDATAFORMAT g_objects[] = {\n")
        f.write("\n".join(rows) + "\n")
        f.write("};\n\n}  // namespace\n\n"
                "const DIDATAFORMAT g_joystickDataFormat = {\n"
                "    sizeof(DIDATAFORMAT), sizeof(DIOBJECTDATAFORMAT), DIDF_ABSAXIS, sizeof(DIJOYSTATE2),\n"
                "    sizeof(g_objects) / sizeof(g_objects[0]), g_objects,\n"
                "};\n")
    print("wrote", out, count, "objects")


if __name__ == "__main__":
    main()
