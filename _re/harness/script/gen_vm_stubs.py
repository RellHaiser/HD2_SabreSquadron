"""Writes vm_stubs.s: a link stub for every symbol script_vm.cpp and script_functions.cpp reach that the interpreter test
(vm_diff.cpp) does not link (the game: actors, humans, teams, the engine, ...). A function's stub reports the call and
ends the test (VmUnexpected); a variable's is 64 KB of zeros. Run it when build_vm.bat's link reports an undefined
reference (the port's symbols changed): python gen_vm_stubs.py, then build_vm.bat.

It links once without the stubs (MinGW's g++ on the PATH, as build_vm.bat sets it), with --no-demangle, and reads the
undefined references from the errors; c++filt tells a function (a parameter list) from a variable."""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MINGW = r"C:\nim-2.2.6\dist\mingw32\bin"


def main():
    env = dict(os.environ, PATH=MINGW + os.pathsep + os.environ["PATH"])
    bat = open(os.path.join(HERE, "build_vm.bat"), encoding="latin-1").read()
    m = re.search(r"^g\+\+ (.*vm_diff\.exe.*)$", bat, re.M)
    if not m:
        sys.exit("gen_vm_stubs: no g++ line in build_vm.bat")
    src = r"..\..\..\src"
    line = m.group(1).replace("%SRC%", src).replace(" vm_stubs.s", "")
    tmp = os.environ.get("TEMP", HERE)
    probe = '-o "%s"' % os.path.join(tmp, "vm_probe.exe")
    line = re.sub(r'-o "[^"]*"', lambda _: probe, line)
    line = line.replace(" 2>&1", "") + " -Wl,--no-demangle"
    p = subprocess.run("g++ " + line, cwd=HERE, env=env, shell=True, capture_output=True, text=True)
    names = sorted(set(re.findall(r"undefined reference to `([^']+)'", p.stdout + p.stderr)))
    if not names:
        print(p.stdout + p.stderr)
        sys.exit("gen_vm_stubs: no undefined references (nothing to write, or another error above)")
    demangled = subprocess.run(["c++filt"], input="\n".join(names), env=env, capture_output=True, text=True,
                               shell=True).stdout.splitlines()
    out = ["# vm_stubs.s: GENERATED by gen_vm_stubs.py (link stubs for vm_diff.exe); do not edit by hand.", ""]
    functions = variables = 0
    for name, plain in zip(names, demangled):
        asm = name                                      # (the assembler's name: its underscore included)
        out.append("# " + plain)
        if "(" in plain and not plain.startswith(("vtable for", "typeinfo")):
            functions += 1
            out += ["\t.text", "\t.globl\t%s" % asm, "%s:" % asm, "\tpushl\t$%s_name" % asm, "\tcall\t_VmUnexpected",
                    "\t.section .rdata,\"dr\"", "%s_name:" % asm, '\t.asciz\t"%s"' % plain.replace('"', "'"), ""]
        else:
            variables += 1
            out += ["\t.bss", "\t.align\t16", "\t.globl\t%s" % asm, "%s:" % asm, "\t.space\t65536", ""]
    open(os.path.join(HERE, "vm_stubs.s"), "w", newline="\r\n").write("\n".join(out) + "\n")
    print("gen_vm_stubs: %d functions, %d variables" % (functions, variables))


main()
