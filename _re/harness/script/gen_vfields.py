"""gen_vfields.py HEADER OUT.inc STRUCT...: from HEADER's struct / class definitions whose members carry the original's
offsets ("// +0xNNN"), writes C++ that prints each such member on the current side (H::g_side: 1 the original's bytes at
the offsets, 0 the port's members), one line a member: "<prefix>.<name> <value>". Nested structs of the header with
offsets are printed member by member; std::vector reads the original's MSVC 6 layout (first +4, last +8), std::string its
char * (null: empty). Members without an offset are the port's own and left out."""
import re
import sys

headers, out_path = sys.argv[1].split(','), sys.argv[2]
header = headers[0]
wanted = sys.argv[3:]
text = '\n'.join(open(h, encoding='latin-1').read() for h in headers)

# The structs: name -> (size, [(type, name, dims, offset)]).
structs = {}
for m in re.finditer(r'^(?:struct|class)(?:\s+alignas\(\d+\))?\s+(\w+)(?:\s+final)?(?:\s*:\s*public\s+\w+)?\s*\{([^\n]*)\n(.*?)^\};',
                     text, re.M | re.S):
    name, first, body = m.group(1), m.group(2), m.group(3)
    sm = re.search(r'\b(0x[0-9A-Fa-f]+|\d+) bytes', first)
    size = sm.group(1) if sm else None
    if not size:
        am = re.search(r'sizeof\(%s\) == (0x[0-9A-Fa-f]+|\d+)' % name, text)
        size = am.group(1) if am else None
    members = []
    for line in body.split('\n'):
        mm = re.match(r'\s+((?:const\s+)?[A-Za-z_][\w:<>, \*]*?[\s\*]+)(\w+)((?:\[[^\]]+\])*)\s*(?:=[^;]*)?;\s*//\s*\+(0x[0-9A-Fa-f]+)', line)
        if not mm:
            continue
        t, n, dims, off = mm.group(1).strip(), mm.group(2), mm.group(3), int(mm.group(4), 16)
        if '(' in t:
            continue
        dims = [d for d in re.findall(r'\[([^\]]+)\]', dims)]
        members.append((t, n, dims, off))
    structs[name] = (int(size, 0) if size else None, members)

SIMPLE = {
    'float': ('float', 'Fl({})'),
    'double': ('double', 'F("%.17g", {})'),
    'int': ('int', 'F("%d", {})'), 'int32_t': ('int32_t', 'F("%d", {})'), 'long': ('int32_t', 'F("%d", int({}))'),
    'uint32_t': ('uint32_t', 'F("%x", {})'), 'unsigned': ('uint32_t', 'F("%x", {})'),
    'int16_t': ('int16_t', 'F("%d", int({}))'), 'uint16_t': ('uint16_t', 'F("%d", int({}))'),
    'int8_t': ('int8_t', 'F("%d", int({}))'), 'uint8_t': ('uint8_t', 'F("%d", int({}))'), 'char': ('char', 'F("%d", int({}))'),
    'bool': ('uint8_t', 'F("%d", int({}))'),
}
# (S_vector4: x, y, z only; the original leaves most w components as stack leftovers.)
VECTORS = {'S_vector': 3, 'S_vector4': 3, 'S_quat': 4, 'S_plane': 4, 'S_matrix': 16, 'I3D_bbox': 8}
SIZES = {'float': 4, 'double': 8, 'int': 4, 'int32_t': 4, 'long': 4, 'uint32_t': 4, 'unsigned': 4, 'int16_t': 2, 'uint16_t': 2,
         'int8_t': 1, 'uint8_t': 1, 'char': 1, 'bool': 1, 'S_vector': 12, 'S_vector4': 16, 'S_quat': 16, 'S_plane': 16,
         'S_matrix': 64, 'I3D_bbox': 32}

# The std::vector members that are the original's aligned arrays (its _aligned_malloc lists: the data +0, the capacity +4,
# the count +8, the growth +0xC), not MSVC 6 vectors (an allocator word, then first, last, end).
ALIGNED = {'C_Vehicle.m_axleStruts', 'C_Vehicle.m_sideStruts', 'C_Vehicle.m_exhausts', 'C_Vehicle.m_bodyContacts',
           'C_Vehicle.m_seats', 'C_Vehicle.m_doors', 'C_Vehicle.m_ballasts', 'C_Vehicle.m_specialCollisionCorners',
           'C_Vehicle.m_specialCollisions', 'C_Vehicle.m_specialVolumes'}

# The std::vector members that are the original's bare arrays: the data pointer at the member's offset, the element count
# (an int) at the struct's offset given.
COUNTED = {'S_VehicleTrack.vertices': 0xC, 'S_VehicleTrack.offsets': 0xC}

# Members not compared: what the original leaves uninitialised (stack leftovers).
SKIP = {'S_VehicleExhaust.unknown24'}

# Members shown only while a flag of the test is set (the parameter block and what only ApplyParams changes: the test
# shows them after the operations that may change them).
GUARDED = {'C_Vehicle.m_params': 'g_showConstant', 'C_Vehicle.m_layers1': 'g_showConstant',
           'C_Vehicle.m_layers2': 'g_showConstant'}

out = ['// Generated by gen_vfields.py from %s: do not edit.' % header.replace('\\', '/').split('src/')[-1]]
done = set()


def size_of(t):
    t = t.replace('const ', '').strip()
    if t.endswith('*'):
        return 4
    if t.startswith('E_'):
        return 4
    if t in SIZES:
        return SIZES[t]
    if t in structs and structs[t][0]:
        return structs[t][0]
    if t == 'std::string':
        return 4
    if t.startswith('std::vector<'):
        return 16
    return None


def emit_value(t, port_expr, orig_expr, label, lines, indent, aligned=False):
    """One value: its port expression (an lvalue) and the original's address expression (const uint8_t *)."""
    t = t.replace('const ', '').strip()
    pad = ' ' * indent
    if t.endswith('*'):
        lines.append(pad + 'out.push_back(%s + " " + NameOf(g_side ? At<uint32_t>(%s, 0) : Ptr(%s)));' % (label, orig_expr, port_expr))
    elif t.startswith('E_'):
        lines.append(pad + 'out.push_back(%s + F(" %%d", g_side ? At<int>(%s, 0) : int(%s)));' % (label, orig_expr, port_expr))
    elif t in SIMPLE:
        ctype, fmt = SIMPLE[t]
        lines.append(pad + 'out.push_back(%s + " " + (g_side ? %s : %s));' % (label, fmt.format('At<%s>(%s, 0)' % (ctype, orig_expr)),
                                                                          fmt.format('%s(%s)' % (ctype, port_expr))))
    elif t == 'I3D_bbox':
        # (min and max: x, y, z; their w words are leftovers too.)
        lines.append(pad + '{')
        lines.append(pad + '    const uint8_t *b = g_side ? %s : reinterpret_cast<const uint8_t *>(&%s);' % (orig_expr, port_expr))
        lines.append(pad + '    out.push_back(%s + " " + VN(b, 3) + " " + VN(b + 16, 3));' % label)
        lines.append(pad + '}')
    elif t in VECTORS:
        n = VECTORS[t]
        lines.append(pad + 'out.push_back(%s + " " + VN(g_side ? static_cast<const void *>(%s) : static_cast<const void *>(&%s), %d));'
                     % (label, orig_expr, port_expr, n))
    elif t == 'std::string':
        lines.append(pad + 'out.push_back(%s + " " + (g_side ? OrigCStr(At<uint32_t>(%s, 0)) : PortString(%s)));' % (label, orig_expr, port_expr))
    elif t.startswith('std::vector<'):
        inner = t[len('std::vector<'):-1].strip()
        isz = size_of(inner)
        if isz is None:
            lines.append(pad + '// (%s: %s not known)' % (label, t))
            return
        lines.append(pad + '{')
        if aligned:
            lines.append(pad + '    const size_t count = g_side ? size_t(At<int>(%s, 8)) : %s.size();' % (orig_expr, port_expr))
        else:
            lines.append(pad + '    const size_t count = g_side ? OrigCount(%s, %d) : %s.size();' % (orig_expr, isz, port_expr))
        lines.append(pad + '    out.push_back(%s + F(" size %%d", int(count)));' % label)
        lines.append(pad + '    for (size_t k = 0; k < count && k < 64; ++k) {')
        lines.append(pad + '        const uint8_t *oe = g_side ? reinterpret_cast<const uint8_t *>(At<uint32_t>(%s, %d)) + %d * k : nullptr;'
                     % (orig_expr, 0 if aligned else 4, isz))
        emit_value(inner, '%s[k]' % port_expr, 'oe', '%s + F("[%%d]", int(k))' % label, lines, indent + 8)
        lines.append(pad + '    }')
        lines.append(pad + '}')
    elif t in structs and structs[t][1]:
        emit_struct(t)
        lines.append(pad + 'Fields_%s(g_side ? %s : nullptr, g_side ? nullptr : &%s, %s, out);' % (t, orig_expr, port_expr, label))
    else:
        lines.append(pad + '// (%s: type %s not known)' % (label, t))


def emit_struct(name):
    if name in done:
        return
    done.add(name)
    _, members = structs[name]
    lines = ['void Fields_%s(const uint8_t *o, const %s *p, const std::string &prefix, std::vector<std::string> &out)' % (name, name),
             '{']
    for t, n, dims, off in members:
        guard = GUARDED.get('%s.%s' % (name, n))
        if guard:
            lines.append('    if (%s) {' % guard)
        emit_member(name, t, n, dims, off, lines)
        if guard:
            lines.append('    }')
    lines.append('}')
    out.append('\n'.join(lines))


def emit_member(name, t, n, dims, off, lines):
    if '%s.%s' % (name, n) in SKIP:
        lines.append('    // (%s: not compared)' % n)
        return
    if '%s.%s' % (name, n) in COUNTED:
        inner = t[len('std::vector<'):-1].strip()
        isz = size_of(inner)
        lines.append('    {')
        lines.append('        const size_t count = g_side ? size_t(At<int>(o, 0x%X)) : p->%s.size();' % (COUNTED['%s.%s' % (name, n)], n))
        lines.append('        out.push_back(prefix + ".%s" + F(" size %%d", int(count)));' % n)
        lines.append('        for (size_t k = 0; k < count && k < 64; ++k) {')
        lines.append('            const uint8_t *oe = g_side ? reinterpret_cast<const uint8_t *>(At<uint32_t>(o, 0x%X)) + %d * k : nullptr;' % (off, isz))
        emit_value(inner, 'p->%s[k]' % n, 'oe', 'prefix + ".%s" + F("[%%d]", int(k))' % n, lines, 12)
        lines.append('        }')
        lines.append('    }')
        return
    if not dims:
        emit_value(t, 'p->%s' % n, '(o + 0x%X)' % off, 'prefix + ".%s"' % n, lines, 4, '%s.%s' % (name, n) in ALIGNED)
        return
    esz = size_of(t)
    if esz is None:
        lines.append('    // (%s: element size not known)' % n)
        return
    count = ' * '.join('(%s)' % d for d in dims)
    lines.append('    for (int k = 0; k < int(%s); ++k) {' % count)
    flat = '(&p->%s%s)[k]' % (n, '[0]' * len(dims)) if len(dims) > 0 else 'p->%s' % n
    emit_value(t, flat, '(o + 0x%X + %d * k)' % (off, esz), 'prefix + ".%s" + F("[%%d]", k)' % n, lines, 8)
    lines.append('    }')


for w in wanted:
    emit_struct(w)
open(out_path, 'w', newline='\n').write('\n\n'.join(out) + '\n')
print('structs:', ', '.join(sorted(done)))
