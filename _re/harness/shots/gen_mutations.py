"""Generates a mutation list for _re/harness/mutrun.py from a range of lines of a source.

    python gen_mutations.py SOURCE RANGES OUT.py [TITLE]     (RANGES: "304-665" or "348-470,558-578")

SOURCE relative to the repository (src/game/shots.cpp). One mutation per kind per line, only for lines
found once in the file (mutrun replaces the text once):
  del   a statement (ends in ';', not a declaration with an initializer) replaced by ';' (a brace-less
        if keeps its shape: deleting the line would hand the if the next statement)
  cmp   the first comparison flipped: < <=, > >=, == !=, <= <, >= >, != ==
  num   the first number literal changed (x -> x + 1, floats x -> x * 1.5)
  bool  true <-> false
  neg   the first "!" of a condition removed
  arith the first " + " <-> " - ", " * " -> " / "
Comments and preprocessor lines are skipped. Equivalent mutants are not removed: list them by hand.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))


def mutants(line):
    code = line.split("//")[0]
    body = code.strip()
    if not body or body.startswith("#") or body.startswith("//"):
        return
    indent = line[:len(line) - len(line.lstrip())]
    if body.endswith(";") and not re.match(r"(const\s+)?[\w:<>*&\s]+\s[\w]+\s*(=|\{|\()", body) \
            and not body.startswith(("return", "break", "continue", "case", "default")):
        yield "del", indent + ";" + line[len(line.rstrip("\r\n")):]
    for a, b in ((" <= ", " < "), (" >= ", " > "), (" == ", " != "), (" != ", " == "), (" < ", " <= "),
                 (" > ", " >= ")):
        at = code.find(a)
        if at >= 0:
            yield "cmp", line[:at] + b + line[at + len(a):]
            break
    m = re.search(r"(?<![\w.])(\d+\.\d*f?|\d+)(?![\w.])", code)
    if m and not re.search(r"\w$", code[:m.start()]):
        text = m.group(1)
        if "." in text:
            value = float(text.rstrip("f")) * 1.5 if float(text.rstrip("f")) else 1.0
            new = repr(value) + ("f" if text.endswith("f") else "")
        else:
            new = str(int(text) + 1)
        yield "num", line[:m.start()] + new + line[m.end():]
    for a, b in (("true", "false"), ("false", "true")):
        m = re.search(r"\b%s\b" % a, code)
        if m:
            yield "bool", line[:m.start()] + b + line[m.end():]
            break
    m = re.search(r"(if|while) \(!", code)
    if m:
        at = m.end() - 1
        yield "neg", line[:at] + line[at + 1:]
    for a, b in ((" + ", " - "), (" - ", " + "), (" * ", " / ")):
        at = code.find(a)
        if at >= 0:
            yield "arith", line[:at] + b + line[at + len(a):]
            break


def main():
    source, ranges, out = sys.argv[1], sys.argv[2], sys.argv[3]
    title = sys.argv[4] if len(sys.argv) > 4 else "mutations of %s %s" % (source, ranges)
    numbers = [n for r in ranges.split(",") for n in range(int(r.split("-")[0]), int(r.split("-")[1]) + 1)]
    path = os.path.join(ROOT, source)
    text = open(path, encoding="utf-8", newline="").read()
    lines = text.splitlines(keepends=True)
    rows = []
    for no in numbers:
        line = lines[no - 1]
        if text.count(line) != 1:
            continue
        for kind, new in mutants(line):
            if new != line:
                rows.append(("T %d %s" % (no, kind), line, new))
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write('"""%s\n\nRun: set MUT_HARNESS=shots, then python _re/harness/mutrun.py %s WORK [JOBS].\n'
                'Generated by _re/harness/shots/gen_mutations.py (lines unique in the file).\n"""\n' %
                (title, os.path.relpath(out, ROOT).replace(os.sep, "/")))
        f.write("import os\n\nROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), %r))\n"
                % os.path.relpath(ROOT, os.path.dirname(os.path.abspath(out))))
        f.write("T = os.path.join(ROOT, %r)\n\nMUTATIONS = [\n" % source)
        for label, old, new in rows:
            f.write("    (T, %r, %r, %r),\n" % (label, old, new))
        f.write("]\n")
    print(len(rows), "mutations ->", out)


if __name__ == "__main__":
    main()
