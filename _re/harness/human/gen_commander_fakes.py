PORT_T = {'i': 'int', 'b': 'bool', 'a': 'C_Actor *', 'h': 'C_Human *', 'v': 'const S_vector4 &', 'p': 'int *'}
ORIG_T = {'i': 'int', 'b': 'int', 'a': 'void *', 'h': 'void *', 'v': 'const S_vector4 *', 'p': 'int *'}


def nums(params, orig):
    out = []
    names = []
    for k, t in enumerate(params):
        n = 'a%d' % k
        if t == 'i':
            out.append('double(%s)' % n)
        elif t == 'b':
            out.append('double(%s & 0xFF)' % n if orig else 'double(%s)' % n)
        elif t == 'v':
            v = '(*%s)' % n if orig else n
            out += ['%s.x' % v, '%s.y' % v, '%s.z' % v]
        elif t in 'ah':
            names.append(n)
    return out, names


lines = ['// ---- generated by gen_commander_fakes.py: the squad controller\'s methods the commander calls, logged alike on both sides (the',
         '// port\'s by --wrap, the original\'s redirected); the answers in g_cm.', '']
port_lines, orig_lines, redirects = [], [], []
for name, mangled, addr, params, ret in SPEC:
    pp = ', '.join('%s a%d' % (PORT_T[t], k) for k, t in enumerate(params))
    op = ', '.join('%s a%d' % (ORIG_T[t], k) for k, t in enumerate(params))
    prt = {'v': 'void', 'seat': 'bool', 'projectile': 'bool', 'weapon': 'C_Item *'}[ret]
    ort = {'v': 'void', 'seat': 'int', 'projectile': 'int', 'weapon': 'void *'}[ret]
    for orig in (False, True):
        n, actors = nums(params, orig)
        label = '"Sq%s"' % name
        if actors:
            label = '("Sq%s" + %s).c_str()' % (name, ' + '.join('(" " + NameOf(%s))' % a for a in actors))
        body = ['    Log(self, %s, {%s});' % (label, ', '.join(n))]
        if ret == 'seat':
            body.append('    return g_cm.seatWeapon;')
        elif ret == 'projectile':
            body.append('    return g_cm.projectile;')
        elif ret == 'weapon':
            body.append('    if (a3)')
            body.append('        *a3 = 4;')
            body.append('    return g_cm.launcher ? %s : nullptr;' % (
                'OrigWeapon(g_weaponPort[0])' if orig else 'reinterpret_cast<C_Item *>(g_weaponPort[0])'))
        if orig:
            head = '%s AC CM_%s(void *self%s)' % (ort, name, (', ' + op) if op else '')
            orig_lines += [head, '{'] + body + ['}']
            redirects.append('        {0x%08x, FAKE(CM_%s)},' % (addr, name))
        else:
            head = 'extern "C" %s __attribute__((thiscall)) __wrap__ZN17C_SquadController%s(C_SquadController *self%s)' % (
                prt, mangled, (', ' + pp) if pp else '')
            port_lines += [head, '{'] + body + ['}']
lines += port_lines + [''] + orig_lines + ['', 'const std::pair<uint32_t, const void *> CM_REDIRECTS[] = {'] + redirects + ['};', '']
open(sys.argv[1], 'w', newline='\r\n').write('\n'.join(lines))
