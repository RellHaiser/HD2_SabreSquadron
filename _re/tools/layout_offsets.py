"""Where a port class's layout differs from the original's, by its members' offset comments.

Usage: python layout_offsets.py HEADER CLASS [HEADER CLASS ...] [--table OUT.inc]

Reads each class's members that carry a `// +0xNNN` comment (the original's offset), compiles a probe with the
harnesses' MinGW g++ (32-bit, the port's own headers) and prints, per class, the members whose offsetof differs and
the first one that does. With --table, writes an include of S_LayoutField{original offset, port offset, size, name}
rows per class (`LAYOUT_<CLASS>`; the kind: 'p' pointers, 'f' float data, 'i' integers and flags, 'm' other structs), for copying objects into the original's layout (std:: containers and other
members whose size differs are left out and listed: they need a shadow by hand).
"""
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "src")
GXX = r"C:\nim-2.2.6\dist\mingw32\bin\g++.exe"

MEMBER = re.compile(r"^\s*(?!//)(?P<decl>[^;/]*?)\b(?P<name>m_[A-Za-z0-9_]+|[a-z][A-Za-z0-9_]*)\s*(?P<array>\[[^\]]*\])*\s*"
                    r"(?:=[^;]*|\{[^;]*\})?;\s*//\s*\+0x(?P<off>[0-9A-Fa-f]+)")


def class_body(text, cls):
    m = re.search(r"\b(?:class|struct)\s+(?:alignas\(\d+\)\s+)?" + re.escape(cls) + r"\b[^;{]*\{", text)
    if not m:
        sys.exit(f"{cls}: not found")
    depth, i = 1, m.end()
    while depth:
        c = text[i]
        depth += c == "{"
        depth -= c == "}"
        i += 1
    return text[m.end():i - 1]


def members(header, cls):
    text = open(header, encoding="utf-8", errors="replace").read()
    body = class_body(text, cls)
    out = []
    depth = 0
    for line in body.splitlines():
        if depth == 0:
            m = MEMBER.match(line)
            if m and "(" not in m.group("decl") and not m.group("decl").strip().startswith(("return", "using", "typedef")):
                decl = m.group("decl")
                if "*" in decl:
                    kind = "p"
                elif re.search(r"\b(float|S_vector|S_vector2|S_vector4|S_quat|S_matrix|S_plane)\b", decl):
                    kind = "f"
                elif re.search(r"\b(int|bool|char|short|unsigned|uint\d+_t|int\d+_t|E_[A-Za-z]+)\b", decl):
                    kind = "i"
                else:
                    kind = "m"
                out.append((m.group("name"), int(m.group("off"), 16), "std::" in decl, kind))
        depth += line.count("{") - line.count("}")
    return out


def main():
    args = sys.argv[1:]
    table = None
    if "--table" in args:
        i = args.index("--table")
        table = args[i + 1]
        del args[i:i + 2]
    pairs = list(zip(args[0::2], args[1::2]))
    probe = ["#define private public", "#define protected public", "#include <cstddef>", "#include <cstdio>"]
    for header, _ in pairs:
        rel = os.path.relpath(os.path.abspath(header), SRC).replace("\\", "/")
        probe.append(f'#include "{rel}"')
    probe.append("int main() {")
    info = {}
    for header, cls in pairs:
        ms = members(header, cls)
        info[cls] = ms
        for name, off, vec, kind in ms:
            probe.append(f'    std::printf("{cls} {name} %u %u {off} {int(vec)} {kind}\\n",(unsigned)offsetof({cls}, {name}), '
                         f'(unsigned)sizeof({cls}::{name}));')
    probe.append("    return 0;\n}")
    tmp = tempfile.mkdtemp()
    cpp = os.path.join(tmp, "probe.cpp")
    exe = os.path.join(tmp, "probe.exe")
    open(cpp, "w", encoding="utf-8", newline="\n").write("\n".join(probe) + "\n")
    r = subprocess.run([GXX, "-std=c++17", "-faligned-new=8", "-w", "-msse2", "-mfpmath=sse", "-DLS3D_API=", "-DRW_DATA_API=",
                        "-Wno-invalid-offsetof", "-I" + SRC, cpp, "-o", exe], capture_output=True, text=True,
                       env=dict(os.environ, PATH=os.path.dirname(GXX) + os.pathsep + os.environ.get("PATH", "")))
    if r.returncode:
        sys.exit(r.stderr[-4000:])
    rows = {}
    for line in subprocess.run([exe], capture_output=True, text=True).stdout.splitlines():
        cls, name, port, size, orig, vec, kind = line.split()
        rows.setdefault(cls, []).append((name, int(port), int(size), int(orig), vec == "1", kind))
    lines = ["// Generated by _re/tools/layout_offsets.py: {original offset, port offset, size, name, kind} per member with an",
             "// offset comment (std:: containers and members whose size the next comment contradicts left out)."]
    for header, cls in pairs:
        rs = rows.get(cls, [])
        bad = [r for r in rs if r[1] != r[3]]
        print(f"{cls}: {len(rs)} members, {len(bad)} at other offsets" +
              (f" (first: {bad[0][0]} port +0x{bad[0][1]:X}, original +0x{bad[0][3]:X})" if bad else ""))
        ordered = sorted(rs, key=lambda r: r[3])
        lines.append(f"#define LAYOUT_{cls.upper()} \\")
        skipped = []
        for i, (name, port, size, orig, vec, kind) in enumerate(ordered):
            nxt = ordered[i + 1][3] if i + 1 < len(ordered) else None
            if vec or (nxt is not None and orig + size > nxt):
                skipped.append(name)
                continue
            lines.append(f'    S_LayoutField{{0x{orig:X}, {port}, {size}, "{name}", \'{kind}\'}}, \\')
        lines.append("")
        if skipped:
            print(f"  left out of the table: {', '.join(skipped)}")
    if table:
        open(table, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
