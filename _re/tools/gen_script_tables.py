"""Generate src/script/script_opcodes.h and src/script/script_tables.cpp from the
tables extracted out of the executable (_re/script_*.json).

  python gen_script_tables.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(os.path.dirname(ROOT), "src", "script")


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main():
    ops = {int(k): v for k, v in json.load(open(os.path.join(ROOT, "script_opcodes.json"))).items()}
    cmds = json.load(open(os.path.join(ROOT, "script_commands.json")))
    funcs = json.load(open(os.path.join(ROOT, "script_functions.json")))
    kws = json.load(open(os.path.join(ROOT, "script_keywords.json")))
    ops.update({261: "BlockBegin", 262: "BlockEnd", 263: "Evaluate", 274: "Block"})

    h = [
        "// Script command opcodes. GENERATED by _re/tools/gen_script_tables.py from the",
        "// game's command table (0x008338a8), keyword table (0x00835b68) and interpreter",
        "// (0x00416e10); do not edit by hand.",
        "#pragma once",
        "",
        "enum E_ScriptOpcode {",
    ]
    for k in sorted(ops):
        n = ops[k]
        if n.startswith("?"):
            n = "Unknown%d" % k
        h.append(f"    OP_{n} = {k},")
    h.append("    OP_LAST_COMMAND = 263,      // the interpreter accepts opcodes 1..OP_LAST_COMMAND")
    h.append("};")
    open(os.path.join(SRC, "script_opcodes.h"), "w").write("\n".join(h) + "\n")

    c = [
        "// Static script language tables. GENERATED by _re/tools/gen_script_tables.py from",
        "// the executable's data; strings are reproduced verbatim (including original typos).",
        '#include "script/script_tables.h"',
        "",
        "// 0x008338a8: command signatures (terminated by opcode 0).",
        "const S_ScriptCommandDef g_scriptCommandDefs[] = {",
    ]
    for r in cmds:
        t = ", ".join(str(x) for x in r["types"])
        a = ", ".join(f'"{esc(x)}"' for x in r["args"])
        c.append(f"    {{{r['op']}, {{{t}}}, {{{a}}}}},")
    c += ['    {0, {0, 0, 0, 0}, {"", "", "", ""}},', "};", ""]
    c.append("// 0x00832d60: built-in condition functions (terminated by a null name).")
    c.append("const S_ScriptFunctionDef g_scriptFunctionDefs[] = {")
    for r in funcs:
        t = ", ".join(str(x) for x in r["types"])
        a = ", ".join(f'"{esc(x)}"' for x in r["args"])
        c.append(f"    {{\"{r['name']}\", {r['id']}, {{{t}}}, {{{a}}}, \"{esc(r['desc'])}\"}},")
    c += ['    {nullptr, 0, {0, 0, 0, 0}, {"", "", "", ""}, ""},', "};", ""]
    c.append("// 0x00835b68: keywords with their token ids and editor colours (terminated by a null name).")
    c.append("const S_ScriptKeyword g_scriptKeywords[] = {")
    for n, i, col in kws:
        c.append(f'    {{"{esc(n)}", {i}, 0x{col:06X}}},')
    c += ["    {nullptr, 0, 0},", "};"]
    open(os.path.join(SRC, "script_tables.cpp"), "w").write("\n".join(c) + "\n")
    print(len(cmds), "commands,", len(funcs), "functions,", len(kws), "keywords")


if __name__ == "__main__":
    main()
